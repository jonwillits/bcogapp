"""
Copy the generated stimuli into the app, in their final shipped form
(`public/m13/`), with the NOTICE beside the audio. Everything shipped is
16 kHz, 16-bit mono WAV, generated by the scripts beside this one; nothing
is recorded from a person. The training tokens are trimmed to a window
around each burst, from TOKEN_BEFORE_S before it to TOKEN_AFTER_S after it,
and concatenated into one file with an index, so that Step 4 loads one
file. The 21-minute probe stream and the review images are not shipped.

  python -I ship.py <out_dir> <repo_dir>
"""
import sys, os, json, shutil
import numpy as np
import soundfile as sf

TOKEN_BEFORE_S = 0.040
TOKEN_AFTER_S = 0.260
SR = 16000

NOTICE = """Lab 13's sounds, objects, and data: how each was made, and under what license.

Every sound in this folder was made by a computer program, offline, by the scripts in training/m13/ of the app repository. Nothing was recorded from a person.

vowels/, continuum/, stream/: a cascade formant synthesizer of the design described by Klatt (1980), written for this lab (training/m13/klatt.py), licensed with the app (GPL-3.0-or-later). The continuum follows Liberman, Harris, Hoffman, and Griffith (1957), p. 359 and Fig. 1; the stream's syllables follow Saffran, Newport, and Aslin (1996), Experiment 1, p. 612.

syllables/, tokens/, vot/, words/: the text-to-speech model Kokoro-82M (hexgrad/Kokoro-82M on Hugging Face), weights and voice packs under the Apache License 2.0 (the model card: "With Apache-licensed weights, Kokoro can be deployed anywhere"), driven by phoneme strings. The voices used are American English voice packs from that repository, named on screen only as voice 1 to voice 12. The pitch-shifted copies in tokens/ were made with Praat's overlap-add resynthesis through parselmouth (Praat: GPL-3.0; parselmouth: GPL-3.0).

objects/: 24 shapes drawn by training/m13/make_objects.py, licensed with the app.

realspeech.json: counts, a histogram, two shares, and about ten utterances derived from the CHILDES North American English corpora (MacWhinney, B. (2000). The CHILDES Project: Tools for Analyzing Talk, 3rd ed. Lawrence Erlbaum), data from TalkBank (talkbank.org), used under TalkBank's terms (CC BY-NC-SA 3.0). No transcript is shipped; the utterances shipped contain no personal names. Words were turned into syllables with the CMU Pronouncing Dictionary (cmudict 0.7b, Carnegie Mellon University, BSD-style license: see cmudict-LICENSE in this folder).
"""


def main(out, repo):
    pub = os.path.join(repo, "public", "m13")
    audio = os.path.join(pub, "audio")
    os.makedirs(audio, exist_ok=True)
    for sub in ["vowels", "continuum", "stream"]:
        dst = os.path.join(audio, sub)
        os.makedirs(dst, exist_ok=True)
        for f in os.listdir(os.path.join(out, sub)):
            if f.endswith(".wav") and f != "probe_stream.wav":
                shutil.copy(os.path.join(out, sub, f), dst)
        for f in os.listdir(os.path.join(out, sub)):
            if f.endswith(".json"):
                shutil.copy(os.path.join(out, sub, f), os.path.join(pub, f))
    tts = json.load(open(os.path.join(out, "tts", "tts.json")))
    for sub in ["syllables", "vot", "words"]:
        dst = os.path.join(audio, sub)
        os.makedirs(dst, exist_ok=True)
        for f in os.listdir(os.path.join(out, "tts", sub)):
            shutil.copy(os.path.join(out, "tts", sub, f), dst)
    # Tokens: trimmed around the burst, concatenated, re-indexed.
    y, sr = sf.read(os.path.join(out, "tts", "tokens", "tokens.wav"))
    assert sr == SR
    chunks, index, pos = [], [], 0
    before, after = int(TOKEN_BEFORE_S * SR), int(TOKEN_AFTER_S * SR)
    fade = int(0.005 * SR)
    for t in tts["tokens"]["tokens"]:
        s0 = t["start"]
        b = s0 + int(round(t["burstS"] * SR))
        a0, a1 = max(s0, b - before), min(s0 + t["length"], b + after)
        seg = y[a0:a1].copy()
        seg[:fade] *= np.linspace(0, 1, fade)
        seg[-fade:] *= np.linspace(1, 0, fade)
        index.append({**t, "start": pos, "length": len(seg), "burstS": round((b - a0) / SR, 4)})
        chunks.append(seg)
        pos += len(seg)
    dst = os.path.join(audio, "tokens")
    os.makedirs(dst, exist_ok=True)
    sf.write(os.path.join(dst, "tokens.wav"), np.concatenate(chunks).astype(np.float32), SR, subtype="PCM_16")
    tts["tokens"]["tokens"] = index
    tts["tokens"]["trim"] = {"beforeBurstS": TOKEN_BEFORE_S, "afterBurstS": TOKEN_AFTER_S}
    json.dump(tts, open(os.path.join(pub, "tts.json"), "w"), indent=1)
    # Objects and real speech.
    dst = os.path.join(pub, "objects")
    os.makedirs(dst, exist_ok=True)
    for f in os.listdir(os.path.join(out, "objects")):
        if f.endswith(".svg") and f != "sheet.svg" or f.endswith(".json"):
            shutil.copy(os.path.join(out, "objects", f), dst)
    rs = os.path.join(out, "realspeech", "realspeech.json")
    if os.path.exists(rs):
        shutil.copy(rs, pub)
    open(os.path.join(audio, "NOTICE"), "w").write(NOTICE)
    import cmudict
    shutil.copy(os.path.join(os.path.dirname(cmudict.__file__), "data", "LICENSE"), os.path.join(pub, "cmudict-LICENSE"))
    total = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(pub) for f in fs)
    print(f"shipped to {pub}: {total / 1e6:.1f} MB")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
